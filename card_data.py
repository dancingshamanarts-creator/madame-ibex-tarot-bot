# ─── CARD LOOKUP ────────────────────────────────────────────────────
def get_card(name: str):
    """Flexible card lookup — handles partial names, case insensitive."""
    name_clean = name.strip().lower()
    for card_name, card_data in CARDS.items():
        if card_name.lower() == name_clean:
            return card_name, card_data
    for card_name, card_data in CARDS.items():
        if name_clean in card_name.lower():
            return card_name, card_data
    return None
